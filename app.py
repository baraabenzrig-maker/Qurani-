# 3. التبويبات الرئيسية
tab1, tab2, tab3, tab4 = st.tabs(["📖 المصحف", "📻 البث المباشر", "🤖 المساعد الفقهي", "⚙️ الإحصائيات والملاحظات"])

# تبويب المصحف
with tab1:
    st.header("تصفح مصحف المدينة")
    surah_names = [f"{s['id']}. سورة {s['name']} ({s['type']} - {s['verses']} آية)" for s in QURAN_SURAHS]
    sel_idx = st.selectbox("اختر السورة:", range(len(surah_names)), format_func=lambda i: surah_names[i])
    s_info = QURAN_SURAHS[sel_idx]
    st.info(f"سورة **{s_info['name']}** | النوع: {s_info['type']} | الآيات: {s_info['verses']}")
    
    q_folder = "quran_images"
    if os.path.exists(q_folder):
        imgs = sorted([f for f in os.listdir(q_folder) if f.lower().endswith(('png', 'jpg', 'jpeg'))])
    else:
        imgs = []

    if imgs:
        if 'p_num' not in st.session_state: st.session_state.p_num = 0
        c1, c2, c3 = st.columns([1, 2, 1])
        with c1:
            if st.button("⬅️ السابق") and st.session_state.p_num > 0: st.session_state.p_num -= 1
        with c2:
            st.session_state.p_num = st.number_input("الصفحة:", 0, len(imgs)-1, st.session_state.p_num)
        with c3:
            if st.button("التالي ➡️") and st.session_state.p_num < len(imgs)-1: st.session_state.p_num += 1
        st.image(os.path.join(q_folder, imgs[st.session_state.p_num]), use_column_width=True)
    else:
        st.warning(f"الرجاء إنشاء مجلد باسم '{q_folder}' وضع صور صفحات المصحف داخله.")

